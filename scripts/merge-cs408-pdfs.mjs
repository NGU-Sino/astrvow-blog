// 合并函数
// ============================================================
async function mergePdfs(srcDir, dstDir, mergeMap, subjectLabel) {
	if (!existsSync(dstDir)) {
		await mkdir(dstDir, { recursive: true });
	}

	let success = 0;
	let skipped = 0;
	let failed = 0;

	for (const item of mergeMap) {
		const dstPath = path.join(dstDir, item.out);

		if (item.files.length === 0) {
			console.log(`[跳过] ${subjectLabel}/${item.out} - 无源文件`);
			skipped++;
			continue;
		}

		try {
			const mergedPdf = await PDFDocument.create();

			for (const relPath of item.files) {
				const srcPath = path.join(srcDir, relPath);
				if (!existsSync(srcPath)) {
					console.warn(`[警告] 文件不存在: ${relPath}`);
					continue;
				}
				const fileBytes = await readFile(srcPath);
				const srcPdf = await PDFDocument.load(fileBytes, { ignoreEncryption: true });
				const pages = await mergedPdf.copyPages(srcPdf, srcPdf.getPageIndices());
				for (const page of pages) {
					mergedPdf.addPage(page);
				}
			}

			const mergedBytes = await mergedPdf.save();
			await writeFile(dstPath, mergedBytes);
			console.log(`[成功] ${subjectLabel}/${item.out} (${item.files.length} 个源文件)`);
			success++;
		} catch (err) {
			console.error(`[失败] ${subjectLabel}/${item.out}: ${err.message}`);
			failed++;
		}
	}

	console.log(`\n${subjectLabel} 汇总: 成功 ${success}, 跳过 ${skipped}, 失败 ${failed}\n`);
}

// ============================================================
// 主函数
// ============================================================
async function main() {
	console.log("=".repeat(60));
	console.log("开始合并 408 三科 PDF");
	console.log("=".repeat(60));

	await mergePdfs(CO_SRC, CO_DST, CO_MERGE_MAP, "组成原理");
	await mergePdfs(OS_SRC, OS_DST, OS_MERGE_MAP, "操作系统");
	await mergePdfs(CN_SRC, CN_DST, CN_MERGE_MAP, "计算机网络");

	console.log("=".repeat(60));
	console.log("全部合并完成！");
	console.log("=".repeat(60));
}

main().catch((err) => {
	console.error("运行出错:", err);
	process.exit(1);
});
